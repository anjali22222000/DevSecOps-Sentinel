#!/usr/bin/env python3
"""Run pytest and write docs/TEST_RESULTS.md with per-file counts from the real run."""
from __future__ import annotations

import datetime
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
xml_path = Path(tempfile.mkdtemp()) / "junit.xml"
proc = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={xml_path}", "-p", "no:cacheprovider"],
                      cwd=ROOT, capture_output=True, text=True)
root = ET.parse(xml_path).getroot()
suite = root if root.tag == "testsuite" else root.find("testsuite")
per_file = defaultdict(lambda: [0, 0, 0, 0])      # total, passed, failed, skipped
for case in suite.iter("testcase"):
    f = case.get("classname", "").split(".")[1] if "." in case.get("classname", "") else case.get("classname", "")
    row = per_file[f]
    row[0] += 1
    if case.find("failure") is not None or case.find("error") is not None:
        row[2] += 1
    elif case.find("skipped") is not None:
        row[3] += 1
    else:
        row[1] += 1
tot = [sum(r[i] for r in per_file.values()) for i in range(4)]
purpose = {
    "test_names": "package-name normalization (PEP 503, NPM scopes)", "test_privacy": "URL credential/query redaction",
    "test_npm_parser": "package.json and package-lock.json v1/v2/v3 parsing", "test_python_parser": "requirements.txt parsing rules",
    "test_pipfile": "Pipfile.lock parsing (secondary priority)", "test_scan_directory": "file discovery and error/warning policy",
    "test_fetcher": "HTTP timeouts, retry/backoff, Retry-After, size cap, concurrency, redirects (real local server)",
    "test_registry_parsers": "NPM/PyPI name validation and response parsing, malformed responses",
    "test_registry_clients": "found / not-found / error distinction, dedupe, cache rules", "test_bounded_cache": "LRU cache bound",
    "test_registry_fixture": "fixture-based registry evidence", "test_similarity": "Levenshtein/Damerau, false-positive filters",
    "test_versions": "semver and PEP 440 comparison", "test_scoring": "formula, floors, every severity boundary",
    "test_config": "sentinel.toml validation, unknown keys, weights", "test_analyzer": "indicator calculation and finding scenarios",
    "test_policy": "blocking decision, exit codes, scanner-error handling", "test_reports": "JSON/HTML/SARIF agreement, SARIF validation, escaping",
    "test_cli": "CLI basics and registry flag behaviour", "test_cli_scenarios": "end-to-end demo scenarios and exit codes",
    "test_workflows": "static security checks of the GitHub Actions files",
}
md = ["# Automated test results (observed)", "",
      f"Generated by `scripts/summarize_tests.py` on {datetime.date.today()} (Python {platform.python_version()}, {platform.platform()}).", "",
      f"**{tot[1]} passed, {tot[2]} failed, {tot[3]} skipped, {tot[0]} total.**", "",
      "| Test file | Tests | Passed | Failed | What it covers |", "|---|---|---|---|---|"]
for f in sorted(per_file):
    r = per_file[f]
    md.append(f"| {f}.py | {r[0]} | {r[1]} | {r[2]} | {purpose.get(f, '')} |")
md += ["", "## What these tests do not prove", "",
       "- The GitHub Actions workflows and SARIF upload were not executed on GitHub; only static checks and a local simulation of the action's shell steps ran.",
       "- Live registry behaviour is covered by the scenarios in `docs/SCENARIOS.md`, not by this suite (the suite never touches the network).",
       "- The dashboard is checked separately in jsdom by `scripts/run_dashboard_check.sh`; layout and responsiveness were not verified in a real browser.", ""]
(ROOT / "docs" / "TEST_RESULTS.md").write_text("\n".join(md), encoding="utf-8")
print(proc.stdout.strip().splitlines()[-1])
print(f"passed={tot[1]} failed={tot[2]} skipped={tot[3]} total={tot[0]}")
sys.exit(proc.returncode)
