#!/usr/bin/env python3
"""Measure scan time. Writes docs/PERFORMANCE.md. Numbers are only valid for the environment printed in it."""
from __future__ import annotations

import asyncio
import datetime
import os
import platform
import statistics
import subprocess
import sys
import time
from pathlib import Path

import aiohttp
from aiohttp import web
from aiohttp.test_utils import TestServer

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sentinel.analyzer import analyze                      # noqa: E402
from sentinel.config import Config                         # noqa: E402
from sentinel.models import Dependency, Ecosystem, Origin, ParseResult, SourceType  # noqa: E402
from sentinel.registry import RegistryInspector            # noqa: E402
from sentinel.registry.http import Fetcher                 # noqa: E402

LATENCY = 0.05      # simulated server latency per request, seconds
RUNS = 5


def make_app(latency: float) -> web.Application:
    async def npm(request):
        await asyncio.sleep(latency)
        name = request.path[1:]
        return web.json_response({"name": name, "dist-tags": {"latest": "1.0.0"}, "versions": {"1.0.0": {}}})

    async def pypi(request):
        await asyncio.sleep(latency)
        name = request.match_info["name"]
        return web.json_response({"info": {"name": name, "version": "1.0"},
                                  "releases": {"1.0": [{"upload_time_iso_8601": "2020-01-01T00:00:00Z"}]}})
    app = web.Application()
    app.router.add_get("/pypi/{name}/json", pypi)
    app.router.add_get("/{name:.*}", npm)
    return app


def deps(n: int) -> list[Dependency]:
    out = []
    for i in range(n):
        eco = Ecosystem.NPM if i % 2 == 0 else Ecosystem.PYPI
        out.append(Dependency(name=f"sample-package-{i:04d}", ecosystem=eco, origin=Origin.MANIFEST,
                              source_file="package.json", section="dependencies", pinned_version="1.0.0",
                              source_type=SourceType.REGISTRY))
    return out


async def one_run(n: int, concurrency: int, latency: float):
    async with TestServer(make_app(latency)) as server:
        base = str(server.make_url("/")).rstrip("/")
        async with Fetcher(timeout=10, concurrency=concurrency, trust_env=False) as fetcher:
            inspector = RegistryInspector(fetcher, npm_base_url=base, pypi_base_url=base)
            d = deps(n)
            t0 = time.perf_counter()
            evidence = await inspector.inspect(d)
            t_lookup = time.perf_counter() - t0
            t0 = time.perf_counter()
            await inspector.inspect(d)
            t_cached = time.perf_counter() - t0
    t0 = time.perf_counter()
    analyze(ParseResult(dependencies=d), evidence, Config(), Path("."))
    t_analyze = time.perf_counter() - t0
    return t_lookup, t_cached, t_analyze


def main() -> None:
    rows = []
    for n in (10, 50, 100, 200):
        for conc in (1, 10):
            results = [asyncio.run(one_run(n, conc, LATENCY)) for _ in range(RUNS)]
            ideal = n * LATENCY / conc
            rows.append((n, conc, statistics.median(r[0] for r in results), ideal,
                         statistics.median(r[1] for r in results), statistics.median(r[2] for r in results)))
            print(rows[-1])

    live = []
    if os.environ.get("SKIP_LIVE") != "1":
        for _ in range(5):
            t0 = time.perf_counter()
            p = subprocess.run([sys.executable, "-m", "sentinel", "scan", "examples/acme-demo-fixture", "--registry"],
                               cwd=ROOT, capture_output=True, text=True)
            live.append((time.perf_counter() - t0, p.returncode))

    md = ["# Performance measurements", "",
          f"Generated by `scripts/benchmark.py` on {datetime.date.today()}.", "",
          "## Environment", "",
          f"- Python {platform.python_version()}, aiohttp {aiohttp.__version__}, {platform.platform()}, {os.cpu_count()} CPU(s)",
          "- A shared sandbox, not a dedicated benchmark machine; expect run-to-run noise.", "",
          "## A. Controlled test: local mock registry with fixed latency", "",
          f"A local aiohttp server answers every request after a fixed {int(LATENCY*1000)} ms delay, so this isolates the scanner's own "
          f"overhead and the benefit of concurrency. Median of {RUNS} runs. **This is not real registry latency.**", "",
          "| Packages | Concurrency | Median lookup time | Ideal (n x latency / concurrency) | Median cached re-run | Median analysis time |",
          "|---|---|---|---|---|---|"]
    for n, conc, lookup, ideal, cached, analysis in rows:
        md.append(f"| {n} | {conc} | {lookup:.3f} s | {ideal:.3f} s | {cached*1000:.1f} ms | {analysis*1000:.1f} ms |")
    if live:
        times = sorted(t for t, _ in live)
        md += ["", "## B. Real registries: `sentinel scan examples/acme-demo-fixture --registry`", "",
               f"13 unique packages, {len(live)} consecutive runs from this sandbox (includes Python start-up). "
               f"Wall time min / median / max: **{times[0]:.2f} s / {statistics.median(times):.2f} s / {times[-1]:.2f} s**; "
               f"exit codes: {sorted({c for _, c in live})}.", "",
               "This is one small project from one network location at one time; it says nothing about large projects or other networks."]
    md += ["", "## What can and cannot be concluded", "",
           "- The proposal's target of **under 5 seconds** is met at the default concurrency (10) for every size measured "
           "(up to 200 packages at 50 ms simulated latency). It is **not** met with concurrency 1 from 100 packages upward, "
           "which shows the speed comes from the concurrent lookups.",
           "- The 50 ms latency is an assumption chosen for the controlled test; real registry latency varies (see section B for one observed sample).",
           "- It is **not** proven for arbitrary projects: a project with thousands of transitive packages, a slower network, "
           "or registry rate limiting (HTTP 429 with `Retry-After`) can take longer. The retry logic is covered by tests, not by a load test.",
           "- Cached re-runs only help within one process; there is no on-disk cache.", ""]
    (ROOT / "docs" / "PERFORMANCE.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote docs/PERFORMANCE.md")


if __name__ == "__main__":
    main()
